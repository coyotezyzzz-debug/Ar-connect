-- Ajusta colunas de identidade para permitir inserção flexível
alter table if exists public.technicians alter column id set generated by default;
alter table if exists public.reviews alter column id set generated by default;
alter table if exists public.bookings alter column id set generated by default;
alter table if exists public.clients alter column id set generated by default;

-- Remove políticas se já existirem para evitar duplicidade
drop policy if exists "Permitir inserção de técnicos pelo painel" on public.technicians;
drop policy if exists "Permitir atualização de técnicos pelo painel" on public.technicians;
drop policy if exists "Permitir exclusão de técnicos pelo painel" on public.technicians;

-- Cria políticas para anon e authenticated gerenciarem técnicos diretamente
create policy "Permitir inserção de técnicos pelo painel"
  on public.technicians
  for insert
  to anon, authenticated
  with check (true);

create policy "Permitir atualização de técnicos pelo painel"
  on public.technicians
  for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "Permitir exclusão de técnicos pelo painel"
  on public.technicians
  for delete
  to anon, authenticated
  using (true);
